"""Smooth label lines for the named rivers, for the Wheeler lab demo.

Run from the repo root: uv run --project pipeline python review/stage-8/wheeler/river_label_lines.py
Writes site/src/lab/wheeler/riverLines.ts.

The site's river lines are traced through the 1:50,000 INEGI and NHD networks (tiles/rivers.py), so they follow
every meander. MapLibre will not set a line label across bends sharper than its angle limit, so on the traced
rivers the names hardly ever find room: the Bavispe shows no name at zoom 9, nor the Santa María at 11.
Wheeler letters a river along its general run, not its bends. This makes that general run: each named Natural Earth
river (both of the layers tiles/build_base.py uses, public domain) clipped to the story box, its parts merged,
simplified to SIMPLIFY degrees and rounded with two passes of Chaikin's corner cutting. The lines are only for
placing names; they are never drawn.
"""

import json
import subprocess
import tempfile
from pathlib import Path

import shapely
from shapely.geometry import mapping, shape
from shapely.ops import linemerge, unary_union

REPO = Path(__file__).resolve().parents[3]
PRIVATE = REPO / 'private' if (REPO / 'private').exists() else Path('/Users/jb/repos/crossing-map/private')
NE = PRIVATE / 'cache' / 'basemap'
OUT = REPO / 'site' / 'src' / 'lab' / 'wheeler' / 'riverLines.ts'
BOX = ['-113.5', '26.5', '-103.5', '36.5']
# About 3 km: enough to take out the meanders and keep the river's turns.
SIMPLIFY = 0.03
# tiles/rivers.py: the Aros-Bavispe confluence.
YAQUI_STARTS = 29.53
MIN_LENGTH = 0.15
LAYERS = {'ne_10m_rivers_lake_centerlines': 'major', 'ne_10m_rivers_north_america': 'minor'}


def chaikin(coords, passes=2):
    for _ in range(passes):
        out = [coords[0]]
        for (x0, y0), (x1, y1) in zip(coords, coords[1:]):
            out += [(0.75 * x0 + 0.25 * x1, 0.75 * y0 + 0.25 * y1), (0.25 * x0 + 0.75 * x1, 0.25 * y0 + 0.75 * y1)]
        out.append(coords[-1])
        coords = out
    return coords


def main():
    feats = []
    with tempfile.TemporaryDirectory() as tmp:
        for layer, rank in LAYERS.items():
            dst = Path(tmp) / f'{layer}.geojson'
            subprocess.run(['ogr2ogr', '-f', 'GeoJSON', '-spat', *BOX, '-clipsrc', 'spat_extent', '-dialect', 'OGRSQL',
                            '-sql', f'SELECT name, scalerank FROM {layer}', str(dst), str(NE / layer / f'{layer}.shp')], check=True)
            by_name: dict[str, list] = {}
            for f in json.loads(dst.read_text())['features']:
                name = f['properties'].get('name')
                if not name:
                    continue
                geom = shape(f['geometry'])
                if name == 'Yaqui':
                    # As in tiles/rivers.py: Natural Earth's "Yaqui" north of the Aros confluence is the Bavispe.
                    north = shapely.box(-180, YAQUI_STARTS, 180, 90)
                    by_name.setdefault('Bavispe', []).append(geom.intersection(north))
                    geom = geom.difference(north)
                by_name.setdefault(name, []).append(geom)
            for name, geoms in by_name.items():
                union = unary_union(geoms)
                merged = linemerge(union) if union.geom_type == 'MultiLineString' else union
                for part in getattr(merged, 'geoms', [merged]):
                    if part.length < MIN_LENGTH:
                        continue
                    simple = part.simplify(SIMPLIFY)
                    line = shapely.LineString([(round(x, 4), round(y, 4)) for x, y in chaikin(list(simple.coords))])
                    feats.append({'type': 'Feature', 'geometry': mapping(line), 'properties': {'name': name, 'rank': rank}})
    print(len(feats), 'label lines:', sorted({f['properties']['name'] for f in feats}))
    body = json.dumps({'type': 'FeatureCollection', 'features': feats}, ensure_ascii=False)
    OUT.write_text(
        '// Generated by review/stage-8/wheeler/river_label_lines.py: smoothed Natural Earth river lines (public domain),\n'
        '// used only to place river names along each river\'s general run.\n'
        "import type { FeatureCollection, LineString } from 'geojson'\n\n"
        f'export const riverLines: FeatureCollection<LineString, {{ name: string; rank: string }}> = {body}\n'
    )


if __name__ == '__main__':
    main()
